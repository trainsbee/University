# Ejercicio #8: Genere la unión lógica y operativa de dos conjuntos de
# datos independientes descritos por {1, 2, 3} y {4, 5, 6}, desplegando el
# conjunto resultante unificado y sin alterar la naturaleza de la estructura.

numberOne = {1, 2, 3}
numberTwo = {4, 5, 6}

union = numberOne.union(numberTwo)

print(union)

